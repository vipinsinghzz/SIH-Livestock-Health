export const getCleanLang = (lang) => {
  if (!lang) return 'hi';
  const clean = lang.toLowerCase().split('-')[0];
  if (clean === 'en') return 'en';
  if (clean === 'mr') return 'mr';
  return 'hi';
};

export const getSpeciesOptions = (lang = 'hi') => {
  const l = getCleanLang(lang);
  return LIVESTOCK_SPECIES.map((sp) => ({
    id: sp.id,
    icon: sp.icon,
    label: sp.name[l] || sp.name.en,
    shortLabel: sp.shortName[l] || sp.shortName.en
  }));
};

export const getBreedsForSpecies = (speciesId = 'Cattle', lang = 'hi') => {
  const l = getCleanLang(lang);
  const found = LIVESTOCK_SPECIES.find((s) => s.id.toLowerCase() === (speciesId || 'Cattle').toLowerCase()) || LIVESTOCK_SPECIES[0];
  return (found.breeds || []).map((b) => ({
    id: b.id,
    label: b[l] || b.en
  }));
};

export const getSpeciesDisplayName = (speciesId, lang = 'hi') => {
  const l = getCleanLang(lang);
  const found = LIVESTOCK_SPECIES.find((s) => s.id.toLowerCase() === (speciesId || '').toLowerCase());
  return found ? (found.shortName[l] || found.shortName.en) : speciesId;
};

export const getBreedDisplayName = (breedId, speciesId, lang = 'hi') => {
  if (!breedId) return '';
  const l = getCleanLang(lang);
  const foundSpecies = LIVESTOCK_SPECIES.find((s) => s.id.toLowerCase() === (speciesId || '').toLowerCase());
  if (foundSpecies) {
    const foundBreed = foundSpecies.breeds.find((b) => b.id.toLowerCase() === breedId.toLowerCase());
    if (foundBreed) return foundBreed[l] || foundBreed.en;
  }
  for (const s of LIVESTOCK_SPECIES) {
    const b = s.breeds.find((br) => br.id.toLowerCase() === breedId.toLowerCase());
    if (b) return b[l] || b.en;
  }
  return breedId;
};
