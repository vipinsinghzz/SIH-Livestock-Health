/**
 * Global translate function.
 * Supports:
 * - t('common.save')
 * - t('common.save', 'Save Fallback')
 * - t('farmer.namaste', { name: 'Ramesh' })
 * - t('farmer.tag', 'Tag: {tag}', { tag: 'IND-102' })
 */
export function t(
  key: string,
  defaultTextOrParams?: string | Record<string, string | number>,
  params?: Record<string, string | number>,
  overrideLang?: AppLanguage
): string {
  const current = overrideLang || currentLanguage;
  let text = translations[current]?.[key];
  if (!text) {
    text = translations.en?.[key];
  }

  let resolvedText = text;
  let finalParams: Record<string, string | number> | undefined;

  if (typeof defaultTextOrParams === 'string') {
    if (!resolvedText) {
      resolvedText = defaultTextOrParams;
    }
    finalParams = params;
  } else if (typeof defaultTextOrParams === 'object' && defaultTextOrParams !== null) {
    finalParams = defaultTextOrParams;
  }

  if (!resolvedText) {
    resolvedText = key;
  }

  if (finalParams) {
    Object.entries(finalParams).forEach(([pKey, pVal]) => {
      resolvedText = resolvedText.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
    });
  }

  return resolvedText;
}

/**
 * Primary React Hook for consuming localization in any component.
 * When language changes anywhere, all subscribed components re-render immediately.
 */
export function useAppLanguage() {
  const [lang, setLang] = useState<AppLanguage>(currentLanguage);

  useEffect(() => {
    if (currentLanguage !== lang) {
      setLang(currentLanguage);
    }
    const listener = (newLang: AppLanguage) => setLang(newLang);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, [lang]);

  const changeLanguage = useCallback(async (newLang: AppLanguage) => {
    await setAppLanguage(newLang);
  }, []);

  const translate = useCallback(
    (
      key: string,
      defaultTextOrParams?: string | Record<string, string | number>,
      params?: Record<string, string | number>
    ) => {
      return t(key, defaultTextOrParams, params, lang);
    },
    [lang]
  );

  return {
    language: lang,
    changeLanguage,
    t: translate,
    isEnglish: lang === 'en',
    isHindi: lang === 'hi',
    isMarathi: lang === 'mr',
  };
}

